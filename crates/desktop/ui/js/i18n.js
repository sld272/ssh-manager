// UI text is written in Chinese and looked up by that text; English comes from the table below.
let current = 'zh-CN';

export function setLanguage(setting) {
  current = setting === 'system' ? (navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en') : setting;
  document.documentElement.lang = current;
}
export const language = () => current;

// English plurals use {n|one|many}, e.g. "{n} {n|host|hosts}".
export function t(text, params) {
  let out = current === 'en' ? (EN[text] ?? text) : text;
  if (params) {
    out = out.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, key, one, many) => (Number(params[key]) === 1 ? one : many));
    out = out.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ''));
  }
  return out;
}

